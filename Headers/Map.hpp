//DRAWING 
void drawPortal1Map() {
	// ALL Floors 
	for (int row = 0; row < ROWS; row++) {
		for (int col = 0; col < COLS; col++) {
			double x = col * TILE_SIZE;
			double y = row * TILE_SIZE;

			if ((row + col) % 2 == 0) iSetColor(120, 180, 100);
			else iSetColor(100, 150, 80);

			iFilledRectangle(x, y, TILE_SIZE, TILE_SIZE);
		}
	}

	//  ALL Obstacles
	for (int row = ROWS - 1; row >= 0; row--) {
		for (int col = 0; col < COLS; col++) {
			double x = col * TILE_SIZE;
			double y = row * TILE_SIZE;
			int tileType = portal1Layout[row][col];

			if (tileType == 1) {
				if ((row + col) % 2 == 0) {
					iSetColor(120, 80, 50);
					iFilledRectangle(x, y, TILE_SIZE, TILE_SIZE);
					iSetColor(80, 40, 20);
				}
				else {
					iSetColor(100, 60, 40);
					iFilledRectangle(x, y, TILE_SIZE, TILE_SIZE);
					iSetColor(60, 30, 10);
				}
				iRectangle(x, y, TILE_SIZE, TILE_SIZE);
			}
			else if (tileType == 2) {
				iSetColor(100, 100, 100);
				iFilledRectangle(x + 8, y + 5, 24, 65);
				iSetColor(150, 150, 150);
				double tipX[] = { x + 8.0, x + 32.0, x + 26.0, x + 14.0 };
				double tipY[] = { y + 70.0, y + 70.0, y + 78.0, y + 78.0 };
				iFilledPolygon(tipX, tipY, 4);
				iSetColor(50, 50, 50);
				iRectangle(x + 8, y + 5, 24, 65);
				iPolygon(tipX, tipY, 4);
			}
			else if (tileType == 3) {
				iSetColor(101, 67, 33);
				iFilledRectangle(x + 18, y + 5, 4, 30);
				iSetColor(34, 100, 34);
				iFilledEllipse(x + 20, y + 45, 18, 15);
				iSetColor(40, 140, 40);
				iFilledEllipse(x + 20, y + 55, 14, 12);
				iSetColor(50, 180, 50);
				iFilledEllipse(x + 20, y + 65, 10, 8);
			}
		}
	}
}